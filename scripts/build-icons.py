#!/usr/bin/env python3
"""Build vendor/fa/: a Font Awesome Free subset containing only the icons DYON uses.

Scans js/, css/, *.html, templates/ and public/ for `fa-<name>` tokens, keeps
those that exist in Font Awesome 6 Free (solid + brands), writes a tiny CSS
file and two woff2 subsets. Run after adding an icon:  python3 scripts/build-icons.py
Source fonts/CSS live in scripts/src (Font Awesome Free, Icons CC BY 4.0, Fonts OFL 1.1).
"""
import re, pathlib, sys
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'scripts' / 'src'
OUT = ROOT / 'vendor' / 'fa'
SCAN_DIRS = ['js', 'css', 'templates', 'app', 'public']
NON_ICON = {'fa-solid', 'fa-brands', 'fa-regular', 'fa-fw', 'fa-spin', 'fa-'}

css_all = (SRC / 'fa-all.css').read_text()
codes = {}
for m in re.finditer(r'\.fa-([a-z0-9-]+)\s*\{\s*--fa:\s*"\\([0-9a-f]+)"', css_all):
    codes['fa-' + m.group(1)] = m.group(2)

def brand_codepoints():
    f = TTFont(SRC / 'fa-brands-400.ttf')
    return set(f.getBestCmap().keys())
BRANDS = brand_codepoints()

used = set()
files = [p for d in SCAN_DIRS if (ROOT / d).exists() for p in (ROOT / d).rglob('*')
         if p.suffix in {'.js', '.css', '.html', '.php', '.json'} and 'vendor' not in p.parts]
files += list(ROOT.glob('*.html'))
for p in files:
    for tok in re.findall(r'fa-[a-z0-9-]+', p.read_text(errors='ignore')):
        if tok not in NON_ICON and tok in codes:
            used.add(tok)
# glyphs referenced in CSS by code (e.g. details summary chevron)
extra_css_codes = {'f078'}

solid_cps, brand_cps = set(), set()
for name in used:
    cp = int(codes[name], 16)
    (brand_cps if cp in BRANDS and name in {'fa-google', 'fa-apple', 'fa-microsoft', 'fa-whatsapp'} else solid_cps).add(cp)
solid_cps |= {int(c, 16) for c in extra_css_codes}

def make(src, cps, out):
    opts = subset.Options(); opts.flavor = 'woff2'; opts.layout_features = []; opts.notdef_outline = True
    font = TTFont(src)
    sub = subset.Subsetter(opts); sub.populate(unicodes=sorted(cps)); sub.subset(font)
    font.flavor = 'woff2'; font.save(out)

OUT.mkdir(parents=True, exist_ok=True)
make(SRC / 'fa-solid-900.ttf', solid_cps, OUT / 'fa-solid-subset.woff2')
make(SRC / 'fa-brands-400.ttf', brand_cps, OUT / 'fa-brands-subset.woff2')

lines = ["/* Font Awesome Free 6.7.2 subset — generated by scripts/build-icons.py. Do not edit.",
         "   License: Icons CC BY 4.0, Fonts SIL OFL 1.1, Code MIT (see LICENSE.txt). */",
         "@font-face{font-family:'Font Awesome 6 Free';font-style:normal;font-weight:900;font-display:block;src:url('fa-solid-subset.woff2') format('woff2')}",
         "@font-face{font-family:'Font Awesome 6 Brands';font-style:normal;font-weight:400;font-display:block;src:url('fa-brands-subset.woff2') format('woff2')}",
         ".fa-solid,.fa-brands,.fas,.fab{-moz-osx-font-smoothing:grayscale;-webkit-font-smoothing:antialiased;display:var(--fa-display,inline-block);font-style:normal;font-variant:normal;line-height:1;text-rendering:auto}",
         ".fa-solid::before,.fa-brands::before{content:var(--fa)}",
         ".fa-solid,.fas{font-family:'Font Awesome 6 Free';font-weight:900}",
         ".fa-brands,.fab{font-family:'Font Awesome 6 Brands';font-weight:400}",
         ".fa-fw{text-align:center;width:1.25em}",
         ".fa-spin{animation:fa-spin 2s linear infinite}@keyframes fa-spin{to{transform:rotate(360deg)}}",
         "@media (prefers-reduced-motion:reduce){.fa-spin{animation:none}}"]
for name in sorted(used):
    lines.append('.%s{--fa:"\\%s"}' % (name, codes[name]))
(OUT / 'icons.css').write_text('\n'.join(lines) + '\n')
print(f'{len(used)} icons → vendor/fa ({(OUT/"fa-solid-subset.woff2").stat().st_size + (OUT/"fa-brands-subset.woff2").stat().st_size} bytes)')
